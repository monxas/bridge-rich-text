// bridge-paste-helper (macOS) — persistent helper for the Bridge Suits
// Stream Deck plugin. Same line protocol as the Windows helper
// (see src/paste-helper.ts) and the same lifecycle:
//
//   1. wait (bounded) until no modifier key is held,
//   2. snapshot every item/type on the general pasteboard,
//   3. offer RTF / HTML / plain text *lazily* (NSPasteboardItemDataProvider),
//      so the helper learns exactly when the target reads them,
//   4. post Cmd+V (and optionally Ctrl+Space in Word) with CGEvent,
//   5. wait until the target has read the data (or a timeout),
//   6. restore the snapshot, unless another app changed the pasteboard.
//
// Posting keyboard events requires the Accessibility permission for the
// responsible app (Stream Deck). Build: scripts/build-helper-macos.sh.

import AppKit
import ApplicationServices
import Carbon.HIToolbox
import CoreText

let helperVersion = "1.0.0"
let flagResetWordFormatting: UInt32 = 1
let modifierWait: TimeInterval = 1.0
let pasteTimeout: TimeInterval = 2.0
let renderQuiet: TimeInterval = 0.25

func writeLine(_ line: String) {
	FileHandle.standardOutput.write((line + "\n").data(using: .utf8)!)
}

struct Request {
	let id: String
	let flags: UInt32
	let text: Data
	let html: Data?
	let rtf: Data?
	var isProbe = false
}

func decodeField(_ field: Substring) -> Data?? {
	if field == "-" { return .some(nil) }
	guard let data = Data(base64Encoded: String(field)) else { return nil }
	return .some(data)
}

struct BadRequest: Error { let id: String }

func parseRequest(_ line: String) -> Result<Request, BadRequest> {
	let fields = line.split(separator: " ", omittingEmptySubsequences: true)
	let id = fields.first.map(String.init) ?? "?"
	if fields.count == 2, fields[1] == "probe", id.count < 64 {
		return .success(Request(id: id, flags: 0, text: Data(), html: nil, rtf: nil, isProbe: true))
	}
	guard fields.count == 5, id.count < 64, let flags = UInt32(fields[1]),
		let text = decodeField(fields[2]), let html = decodeField(fields[3]), let rtf = decodeField(fields[4]),
		let textData = text, !textData.isEmpty
	else { return .failure(BadRequest(id: id)) }
	return .success(Request(id: id, flags: flags, text: textData, html: html, rtf: rtf))
}

let htmlType = NSPasteboard.PasteboardType.html
let rtfType = NSPasteboard.PasteboardType.rtf
let textType = NSPasteboard.PasteboardType.string
// http://nspasteboard.org markers: clipboard managers should not record this content.
let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

/// Virtual key code that types `character` in the current keyboard layout (QWERTY fallback).
func keyCode(for character: String, fallback: CGKeyCode) -> CGKeyCode {
	guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
		let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
	else { return fallback }
	let layoutData = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
	return layoutData.withUnsafeBytes { buffer -> CGKeyCode in
		guard let layout = buffer.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return fallback }
		for code in 0..<128 {
			var deadKeys: UInt32 = 0
			var chars = [UniChar](repeating: 0, count: 4)
			var length = 0
			let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown), 0, UInt32(LMGetKbdType()),
				OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeys, chars.count, &length, &chars)
			if status == noErr, length == 1, String(utf16CodeUnits: chars, count: 1) == character { return CGKeyCode(code) }
		}
		return fallback
	}
}

/// True when macOS uses Ctrl+Space itself (input source switching), so Word would never see it.
func ctrlSpaceTakenBySystem() -> Bool {
	guard let hotkeys = UserDefaults(suiteName: "com.apple.symbolichotkeys")?.dictionary(forKey: "AppleSymbolicHotKeys") else {
		return false
	}
	for id in ["60", "61"] {
		guard let entry = hotkeys[id] as? [String: Any], (entry["enabled"] as? Bool) == true,
			let value = entry["value"] as? [String: Any], let params = value["parameters"] as? [Int], params.count == 3
		else { continue }
		if params[1] == Int(kVK_Space) && params[2] == Int(CGEventFlags.maskControl.rawValue) { return true }
	}
	return false
}

/// Microsoft Word's own scripting interface (Apple Events), used only while
/// Word is the frontmost application. Not VBA, nothing installed in Word.
/// Requires the Automation permission (System Settings > Privacy & Security >
/// Automation); without it every call returns nil and the helper falls back.
enum WordAutomation {
	static let bundleID = "com.microsoft.Word"

	static var isFrontmost: Bool { NSWorkspace.shared.frontmostApplication?.bundleIdentifier == bundleID }

	static func run(_ body: String) -> NSAppleEventDescriptor? {
		let source = "with timeout of 2 seconds\ntell application id \"\(bundleID)\"\n\(body)\nend tell\nend timeout"
		var error: NSDictionary?
		let result = NSAppleScript(source: source)?.executeAndReturnError(&error)
		if let error { writeLine("event word_automation \(error[NSAppleScript.errorMessage] ?? error)".replacingOccurrences(of: "\n", with: " ")) }
		return error == nil ? result : nil
	}

	struct Format {
		var name: String?
		var size: Double?
		var rgb: [Int32]?
	}

	/// Font name, size and RGB colour at the insertion point.
	static func insertionFormat() -> Format? {
		guard isFrontmost, let list = run("get {name, font size, color} of font object of selection"), list.numberOfItems == 3
		else { return nil }
		let name = list.atIndex(1)?.stringValue.flatMap { $0.isEmpty ? nil : $0 }
		let size = (list.atIndex(2)?.doubleValue).flatMap { $0 > 0 && $0 < 1639 ? $0 : nil }
		var rgb: [Int32]?
		if let color = list.atIndex(3), color.numberOfItems == 3 {
			let values = (1...3).compactMap { color.atIndex($0)?.int32Value }
			rgb = values.count == 3 ? values : nil
		}
		return Format(name: name, size: size, rgb: rgb)
	}

	static func quoted(_ text: String) -> String {
		"\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
	}

	/// Gives the insertion point (the text typed next) this formatting again.
	static func restore(_ format: Format) -> Bool {
		guard isFrontmost else { return false }
		var lines: [String] = []
		if let name = format.name { lines.append("set name of font object of selection to \(quoted(name))") }
		if let size = format.size { lines.append("set font size of font object of selection to \(size)") }
		if let rgb = format.rgb {
			// Black is how Word reports "Automatic"; keep it automatic rather than forcing black.
			lines.append(rgb == [0, 0, 0]
				? "set color index of font object of selection to auto"
				: "set color of font object of selection to {\(rgb[0]), \(rgb[1]), \(rgb[2])}")
		}
		return lines.isEmpty || run(lines.joined(separator: "\n")) != nil
	}
}

let suitCharacters: [UniChar] = [0x2660, 0x2663, 0x2665, 0x2666]
/// Text fonts with ♠♣♥♦ glyphs, used when the document font has none (otherwise
/// Word falls back to Apple Color Emoji, which ignores the font colour).
let suitFallbackFonts = ["Arial", "Apple Symbols", "Menlo"]

/// Fonts bundled privately inside Word (Aptos, Calibri, …), invisible to
/// CoreText name lookup. Family/full/PostScript name -> descriptor, loaded once.
let wordPrivateFonts: [String: CTFontDescriptor] = {
	var map: [String: CTFontDescriptor] = [:]
	guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: WordAutomation.bundleID)?
		.appendingPathComponent("Contents/Resources/DFonts"),
		let files = try? FileManager.default.contentsOfDirectory(at: url, includingPropertiesForKeys: nil)
	else { return map }
	for file in files {
		for descriptor in (CTFontManagerCreateFontDescriptorsFromURL(file as CFURL) as? [CTFontDescriptor]) ?? [] {
			for attribute in [kCTFontFamilyNameAttribute, kCTFontDisplayNameAttribute, kCTFontNameAttribute] {
				if let name = CTFontDescriptorCopyAttribute(descriptor, attribute) as? String, map[name.lowercased()] == nil {
					map[name.lowercased()] = descriptor
				}
			}
		}
	}
	return map
}()

/// nil = font not found anywhere (cannot tell).
func fontHasSuitGlyphs(_ name: String) -> Bool? {
	var font = CTFontCreateWithName(name as CFString, 12, nil)
	let names = [CTFontCopyFamilyName(font), CTFontCopyFullName(font), CTFontCopyPostScriptName(font)] as [String]
	if !names.contains(where: { $0.caseInsensitiveCompare(name) == .orderedSame }) {
		guard let descriptor = wordPrivateFonts[name.lowercased()] else { return nil }
		font = CTFontCreateWithFontDescriptor(descriptor, 12, nil)
	}
	var chars = suitCharacters
	var glyphs = [CGGlyph](repeating: 0, count: chars.count)
	return CTFontGetGlyphsForCharacters(font, &chars, &glyphs, chars.count)
}

/// Font to use for the suit: the document font if it can draw the suits, otherwise a text fallback.
func suitFont(for documentFont: String?) -> String? {
	guard let documentFont else { return nil }
	if fontHasSuitGlyphs(documentFont) != false { return documentFont }
	return suitFallbackFonts.first { fontHasSuitGlyphs($0) == true } ?? documentFont
}

final class Helper: NSObject, NSPasteboardItemDataProvider {
	enum State { case idle, waitModifiers, waitPaste }

	let pasteboard = NSPasteboard.general
	var queue: [Request] = []
	var current: Request?
	var payload: Request?  // request whose data is currently offered
	var state = State.idle
	var stateStart = Date()
	var lastRender = Date()
	var renderCount = 0
	var ourChangeCount = -1
	var snapshot: [[(NSPasteboard.PasteboardType, Data)]]?
	var skipped = 0
	var note: [String] = []
	var eof = false
	var timer: Timer?
	var formatToRestore: WordAutomation.Format?

	// MARK: requests

	func enqueue(_ request: Request) {
		queue.append(request)
		startNext()
	}

	func startNext() {
		guard state == .idle else { return }
		guard !queue.isEmpty else {
			restore()
			if eof { exit(0) }
			return
		}
		current = queue.removeFirst()
		note = []
		formatToRestore = nil
		if current!.isProbe { return answerProbe() }
		state = .waitModifiers
		stateStart = Date()
		if timer == nil {
			timer = Timer.scheduledTimer(withTimeInterval: 0.015, repeats: true) { [weak self] _ in self?.tick() }
		}
		tick()
	}

	func answerProbe() {
		let format = WordAutomation.insertionFormat()
		var parts: [String] = []
		if let name = suitFont(for: format?.name) { parts.append("font=\(Data(name.utf8).base64EncodedString())") }
		if let size = format?.size { parts.append("size=\(size)") }
		note = parts
		state = .waitPaste  // so finish() treats it like a completed request
		finish(ok: true)
	}

	func finish(ok: Bool, _ detail: String = "") {
		guard let request = current else { return }
		if ok, let format = formatToRestore, !WordAutomation.restore(format) {
			note.append("could not restore the typing format in Word")
		}
		writeLine(ok ? "\(request.id) ok\(note.isEmpty ? "" : " " + note.joined(separator: "; "))" : "\(request.id) error \(detail)")
		current = nil
		state = .idle
		timer?.invalidate()
		timer = nil
		if ownerLost {
			snapshot = nil
			payload = nil
		}
		startNext()
	}

	var ownerLost: Bool { ourChangeCount >= 0 && pasteboard.changeCount != ourChangeCount }

	func modifiersDown() -> Bool {
		let flags = CGEventSource.flagsState(.combinedSessionState)
		return !flags.intersection([.maskShift, .maskControl, .maskAlternate, .maskCommand]).isEmpty
	}

	func tick() {
		switch state {
		case .idle:
			return
		case .waitModifiers:
			if !modifiersDown() { return beginPaste() }
			if Date().timeIntervalSince(stateStart) >= modifierWait {
				let flags = String(CGEventSource.flagsState(.combinedSessionState).rawValue, radix: 16)
				return finish(ok: false, "modifier_held release Shift/Ctrl/Option/Cmd before pressing the key (flags 0x\(flags))")
			}
		case .waitPaste:
			let now = Date()
			if ownerLost {
				note.append("clipboard changed by another application; left as is")
				return finish(ok: true)
			}
			if renderCount > 0 && now.timeIntervalSince(lastRender) >= renderQuiet { return finish(ok: true) }
			if now.timeIntervalSince(stateStart) >= pasteTimeout {
				if renderCount > 0 { return finish(ok: true) }
				return finish(ok: false, "paste_not_observed the focused application did not read the clipboard")
			}
		}
	}

	func beginPaste() {
		guard let request = current else { return }
		guard AXIsProcessTrusted() else {
			return finish(ok: false, "accessibility_denied allow Stream Deck in System Settings > Privacy & Security > Accessibility")
		}
		if IsSecureEventInputEnabled() {
			return finish(ok: false, "secure_input another application has enabled secure keyboard entry")
		}
		let front = NSWorkspace.shared.frontmostApplication
		if snapshot == nil { takeSnapshot() }
		writePayload(request)

		var chords: [(CGKeyCode, CGEventFlags)] = [(keyCode(for: "v", fallback: CGKeyCode(kVK_ANSI_V)), .maskCommand)]
		if request.flags & flagResetWordFormatting != 0, front?.bundleIdentifier == WordAutomation.bundleID {
			formatToRestore = WordAutomation.insertionFormat()
			if formatToRestore != nil {
				// restored through Word's scripting interface once the paste is done
			} else if ctrlSpaceTakenBySystem() {
				note.append("Ctrl+Space is used by macOS for input sources; Word formatting not reset")
			} else {
				chords.append((CGKeyCode(kVK_Space), .maskControl))
			}
		}
		// Press and release the modifier key itself; the final release carries no
		// flags. Posting only "V with Cmd flag" leaves the system modifier state
		// latched (Ctrl stuck down until the user presses it physically).
		let source = CGEventSource(stateID: .hidSystemState)
		for (key, flags) in chords {
			let modifierKey = CGKeyCode(flags == .maskControl ? kVK_Control : kVK_Command)
			let sequence: [(CGKeyCode, Bool, CGEventFlags)] = [
				(modifierKey, true, flags), (key, true, flags), (key, false, flags), (modifierKey, false, []),
			]
			for (code, down, eventFlags) in sequence {
				guard let event = CGEvent(keyboardEventSource: source, virtualKey: code, keyDown: down) else {
					return finish(ok: false, "event_failed could not create keyboard event")
				}
				event.flags = eventFlags
				event.post(tap: .cghidEventTap)
			}
		}
		state = .waitPaste
		stateStart = Date()
	}

	// MARK: pasteboard

	func takeSnapshot() {
		var items: [[(NSPasteboard.PasteboardType, Data)]] = []
		skipped = 0
		for item in pasteboard.pasteboardItems ?? [] {
			var entries: [(NSPasteboard.PasteboardType, Data)] = []
			for type in item.types {
				if let data = item.data(forType: type) { entries.append((type, data)) } else { skipped += 1 }
			}
			items.append(entries)
		}
		snapshot = items
	}

	func writePayload(_ request: Request) {
		payload = request
		pasteboard.clearContents()
		let item = NSPasteboardItem()
		var types: [NSPasteboard.PasteboardType] = []
		if request.rtf != nil { types.append(rtfType) }
		if request.html != nil { types.append(htmlType) }
		types.append(textType)
		item.setDataProvider(self, forTypes: types)
		item.setData(Data(), forType: transientType)
		item.setData(Data(), forType: autoGeneratedType)
		pasteboard.writeObjects([item])
		ourChangeCount = pasteboard.changeCount
		renderCount = 0
	}

	func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
		guard let request = payload else { return }
		let data: Data?
		switch type {
		case rtfType: data = request.rtf
		case htmlType: data = request.html.map(Helper.htmlDocument)
		case textType: data = request.text
		default: data = nil
		}
		guard let data else { return }
		item.setData(data, forType: type)
		renderCount += 1
		lastRender = Date()
	}

	/// The plugin sends Windows CF_HTML; macOS public.html is the plain HTML document after the header.
	static func htmlDocument(_ cfHtml: Data) -> Data {
		guard let header = String(data: cfHtml.prefix(200), encoding: .utf8),
			let match = header.range(of: #"StartHTML:(\d+)"#, options: .regularExpression),
			let offset = Int(header[match].dropFirst("StartHTML:".count)), offset < cfHtml.count
		else { return cfHtml }
		return cfHtml.subdata(in: offset..<cfHtml.count)
	}

	func restore() {
		guard let items = snapshot else { return }
		defer {
			snapshot = nil
			payload = nil
			ourChangeCount = -1
		}
		if ownerLost { return }  // newer content wins
		pasteboard.clearContents()
		if !items.isEmpty {
			let restored = items.map { entries -> NSPasteboardItem in
				let item = NSPasteboardItem()
				for (type, data) in entries { item.setData(data, forType: type) }
				return item
			}
			if !pasteboard.writeObjects(restored) { writeLine("event restore_failed pasteboard rejected the previous contents") }
		}
		if skipped > 0 { writeLine("event restore_partial \(skipped) clipboard type(s) could not be preserved") }
	}
}

let app = NSApplication.shared
app.setActivationPolicy(.prohibited)
let helper = Helper()

// Ask once for Accessibility (shows the system prompt naming the responsible app, i.e. Stream Deck).
_ = AXIsProcessTrustedWithOptions([kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary)

writeLine("ready \(helperVersion)")
Thread.detachNewThread {
	while let line = readLine(strippingNewline: true) {
		if line.isEmpty { continue }
		DispatchQueue.main.async {
			switch parseRequest(line) {
			case .success(let request): helper.enqueue(request)
			case .failure(let bad): writeLine("\(bad.id) error bad_request malformed request line")
			}
		}
	}
	DispatchQueue.main.async {
		helper.eof = true
		helper.startNext()
	}
}
app.run()
